import Glibc

// MEAD_JNI_STUBS=<path>: at exit, Swift source for every class a program
// asked for that nothing implements. A game's first run writes the skeleton
// of its compatibility layer. The output is sorted, so runs can be compared.

private func swiftType(_ descriptor: Substring) -> String {
    switch descriptor.first {
    case "Z": return "Bool"
    case "B": return "Int8"
    case "C": return "UInt16"
    case "S": return "Int16"
    case "I": return "Int32"
    case "J": return "Int64"
    case "F": return "Float"
    case "D": return "Double"
    default: return descriptor == "Ljava/lang/String;" ? "String?" : "JavaObject?"
    }
}

/// A signature's parameter descriptors, then its return descriptor.
private func descriptors(of signature: String) -> (parameters: [Substring], result: Substring) {
    var parameters: [Substring] = []
    var index = signature.index(after: signature.startIndex)
    while signature[index] != ")" {
        var end = index
        while signature[end] == "[" {
            end = signature.index(after: end)
        }
        if signature[end] == "L" {
            end = signature[end...].firstIndex(of: ";")!
        }
        end = signature.index(after: end)
        parameters.append(signature[index..<end])
        index = end
    }
    return (parameters, signature[signature.index(after: index)...])
}

private func swiftIdentifier(_ text: String) -> String {
    String(text.map { $0.isLetter || $0.isNumber ? $0 : "_" })
}

private func swiftClassName(_ javaName: String) -> String {
    let flat = swiftIdentifier(javaName)
    return flat.prefix(1).uppercased() + flat.dropFirst()
}

extension JavaRuntime {
    /// The stubs for everything unimplemented so far.
    public func generatedStubs() -> String {
        var text = """
        // Generated by mead from what a program asked of the JVM (MEAD_JNI_STUBS).
        // Fill these in, or delete what the program turns out not to need.

        import MeadJNI

        """
        let classes = allClasses().filter(\.isSynthesized).sorted { $0.name < $1.name }
        for definition in classes {
            text += stubClass(definition)
        }
        return text
    }

    private func stubClass(_ definition: JavaClass) -> String {
        var body = ""
        for field in definition.fields.values.filter(\.isSynthesized).sorted(by: { $0.name < $1.name }) {
            let type = swiftType(field.signature[...])
            let zero = type.hasSuffix("?") ? "nil" : (type == "Bool" ? "false" : "0")
            let declaration = field.isStatic ? "nonisolated(unsafe) public static var" : "public var"
            body += "    @JavaField(\"\(field.name)\", signature: \"\(field.signature)\")\n"
            body += "    \(declaration) field_\(swiftIdentifier(field.name)): \(type) = \(zero)\n\n"
        }

        var used = Set<String>()
        let methods = definition.methods.values
            .filter { $0.isSynthesized && !$0.everRegistered && $0.name != "<clinit>" }
            .sorted { ($0.name, $0.signature) < ($1.name, $1.signature) }
        for method in methods {
            let (parameters, result) = descriptors(of: method.signature)
            let types = parameters.map(swiftType)
            let list = types.enumerated().map { "_ a\($0.offset): \($0.element)" }.joined(separator: ", ")
            body += "    @JavaMethod(\"\(method.name)\", signature: \"\(method.signature)\")\n"
            if method.name == "<init>" {
                let declaration = types.isEmpty ? "public override init()" : "public init(\(list))"
                body += "    \(declaration) {\n        super.init()\n    }\n\n"
                continue
            }
            let base = swiftIdentifier(method.name)
            var name = base
            var suffix = 2
            while !used.insert("\(method.isStatic)|\(name)|\(types.joined(separator: ","))").inserted {
                name = "\(base)_\(suffix)"
                suffix += 1
            }
            let start = method.isStatic ? "public static func" : "public func"
            if result == "V" {
                body += "    \(start) `\(name)`(\(list)) {}\n\n"
            } else {
                body += "    \(start) `\(name)`(\(list)) -> \(swiftType(result)) {\n        javaStub()\n    }\n\n"
            }
        }

        // Stubs need something to construct them with, as JavaObject's
        // initializer is not inherited by a class that declares others.
        let header = "@JavaClass(\"\(definition.name)\")\npublic final class \(swiftClassName(definition.name)): JavaObject {\n"
        return "\n" + header + (body.isEmpty ? "" : String(body.dropLast())) + "}\n"
    }

    func installStubWriter() {
        struct Once {
            static let installed: Void = {
                guard getenv("MEAD_JNI_STUBS") != nil else { return }
                atexit {
                    guard let path = getenv("MEAD_JNI_STUBS"), let file = fopen(path, "w") else { return }
                    fputs(JavaRuntime.shared.generatedStubs(), file)
                    fclose(file)
                }
            }()
        }
        _ = Once.installed
    }
}
