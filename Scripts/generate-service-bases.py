#!/usr/bin/env python3
"""Writes mead-framework's service bases: for each of Android 10's AIDL
interfaces named, a class extending its Stub that answers every method the
way a service that doesn't do it would (nothing, false, 0 or null), and says
so in the log once. Mead's services extend these and override what they do.

Usage: generate-service-bases.py <framework classes.jar> <output directory>
The interfaces come from javap on the framework's classes."""

import os
import re
import subprocess
import sys

# Interface, then the base class written for it in mead.server.base.
INTERFACES = [
    ("android.app.IActivityManager", "ActivityManagerBase"),
    ("android.app.IActivityTaskManager", "ActivityTaskManagerBase"),
    ("android.view.IWindowManager", "WindowManagerBase"),
    ("android.view.IWindowSession", "WindowSessionBase"),
    ("android.content.pm.IPackageManager", "PackageManagerBase"),
    ("com.android.internal.view.IInputMethodManager", "InputMethodManagerBase"),
    ("com.android.internal.app.IAppOpsService", "AppOpsServiceBase"),
    ("android.hardware.input.IInputManager", "InputManagerBase"),
]

METHOD = re.compile(r"^\s*public abstract (.+?) (\w+)\((.*)\)( throws [\w.$, ]+)?;$")
NUMERIC = {"byte", "short", "int", "long", "float", "double", "char"}


def split_parameters(text):
    """Parameter types, split at top-level commas (generics hold commas)."""
    types, depth, current = [], 0, ""
    for c in text:
        if c == "<":
            depth += 1
        elif c == ">":
            depth -= 1
        if c == "," and depth == 0:
            types.append(current.strip())
            current = ""
        else:
            current += c
    if current.strip():
        types.append(current.strip())
    return types


def java_type(name):
    return name.replace("$", ".")


def default_return(type_name):
    if type_name == "void":
        return None
    if type_name == "boolean":
        return "false"
    if type_name in NUMERIC:
        return "0"
    return "null"


def base_class(framework, interface, name):
    listing = subprocess.run(["javap", "-public", "-cp", framework, interface],
                             check=True, capture_output=True, text=True).stdout
    methods = []
    for line in listing.splitlines():
        match = METHOD.match(line)
        if not match:
            continue
        returns, method, parameters, throws = match.groups()
        types = [java_type(t) for t in split_parameters(parameters)]
        arguments = ", ".join(f"{t} p{i}" for i, t in enumerate(types))
        body = f'        MeadServices.unimplemented("{interface.rsplit(".", 1)[1]}.{method}");\n'
        value = default_return(returns)
        if value is not None:
            body += f"        return {value};\n"
        methods.append(f"    @Override\n    public {java_type(returns)} {method}({arguments})"
                       f"{java_type(throws or '')} {{\n{body}    }}\n")
    if not methods:
        sys.exit(f"javap listed no methods of {interface}")
    return (f"// Generated by Scripts/generate-service-bases.py from Android 10's\n"
            f"// {interface}; don't edit.\n\n"
            f"package mead.server.base;\n\n"
            f"import mead.server.MeadServices;\n\n"
            f"/** {interface}, with every method answered as by a service that doesn't do it. */\n"
            f"public abstract class {name} extends {java_type(interface)}.Stub {{\n"
            + "\n".join(methods) + "}\n")


def main():
    framework, output = sys.argv[1], sys.argv[2]
    directory = os.path.join(output, "mead", "server", "base")
    os.makedirs(directory, exist_ok=True)
    for interface, name in INTERFACES:
        with open(os.path.join(directory, f"{name}.java"), "w") as file:
            file.write(base_class(framework, interface, name))


main()
