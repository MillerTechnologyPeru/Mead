#!/bin/sh
# Writes the table that translates bionic's sysconf and pathconf names to
# glibc's: every _SC_ and _PC_ both C libraries define, bionic's number
# beside glibc's name. The numbers come from the NDK's unistd.h; run it in
# the Docker image, and commit the result.
# Usage: MEAD_NDK=/opt/mead-ndk Scripts/generate-bionic-tables.sh
set -eu
cd "$(dirname "$0")/.."
ndk=${MEAD_NDK:-/opt/mead-ndk}
toolchain=$ndk/toolchains/llvm/prebuilt/linux-x86_64
target=Sources/CMeadBionic/bionic_conf_names.inc
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

names() {
    grep -oE '#define _(SC|PC)_[A-Z0-9_]+' | awk '{print $2}' | sort -u
}
printf '#define _GNU_SOURCE\n#include <unistd.h>\n' > "$work/probe.c"
clang-19 -E -dM "$work/probe.c" | names > "$work/glibc.txt"
clang-19 --target=aarch64-linux-android35 --sysroot=$toolchain/sysroot \
    -resource-dir=$toolchain/lib/clang/19 -E -dM "$work/probe.c" | names > "$work/bionic.txt"
comm -12 "$work/bionic.txt" "$work/glibc.txt" > "$work/both.txt"

# The values, printed by a program that sees bionic's names only.
{
    printf '#define _GNU_SOURCE\n#include <stdio.h>\n#include <unistd.h>\nint main(void) {\n'
    while read -r name; do
        printf '    printf("%%s %%d\\n", "%s", (int)(%s));\n' "$name" "$name"
    done < "$work/both.txt"
    printf '    return 0;\n}\n'
} > "$work/values.c"
clang-19 --target=aarch64-linux-android35 --sysroot=$toolchain/sysroot \
    -resource-dir=$toolchain/lib/clang/19 --rtlib=compiler-rt -fuse-ld=lld -static \
    -o "$work/values" "$work/values.c"

{
    echo "// Generated by Scripts/generate-bionic-tables.sh: bionic's number for each"
    echo "// sysconf and pathconf name, and glibc's name for it."
    "$work/values" | awk '{ printf "%s(%s, %s)\n", substr($1, 2, 2), $2, $1 }'
} > "$target"
wc -l "$target"
